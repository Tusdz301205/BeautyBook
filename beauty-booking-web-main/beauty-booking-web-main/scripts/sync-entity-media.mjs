import fs from 'node:fs/promises';
import path from 'node:path';

const frontendRoot = process.cwd();
const planPath = path.resolve(frontendRoot, '..', '..', 'docs', 'generated-images', 'beautybook', 'entity-plan.json');
const outputPath = path.resolve(frontendRoot, 'src', 'config', 'entityMedia.generated.js');

const groupConfig = {
  businesses: { exportName: 'businessMediaById', sizes: '(max-width: 720px) 92vw, (max-width: 1200px) 48vw, 560px' },
  branches: { exportName: 'branchMediaById', sizes: '(max-width: 720px) 92vw, (max-width: 1200px) 48vw, 560px' },
  services: { exportName: 'serviceMediaById', sizes: '(max-width: 720px) 92vw, (max-width: 1200px) 32vw, 420px' },
};

async function exists(file) {
  try {
    await fs.access(file);
    return true;
  } catch {
    return false;
  }
}

function browserPathToFile(value) {
  return path.resolve(frontendRoot, 'public', value.replace(/^\/+/, ''));
}

function renderMedia(entry, sizes) {
  const outputs = [...entry.outputs].sort((a, b) => a.width - b.width);
  const largest = outputs.at(-1);
  return {
    src: largest.path,
    srcSet: outputs.map((item) => `${item.path} ${item.width}w`).join(', '),
    sizes,
    width: largest.width,
    height: largest.height,
    alt: entry.alt,
    illustration: true,
  };
}

let plan = {};
try {
  plan = JSON.parse(await fs.readFile(planPath, 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const lines = [
  '// Generated by scripts/sync-entity-media.mjs. Do not edit by hand.',
  '',
];

for (const [group, config] of Object.entries(groupConfig)) {
  const media = {};
  for (const entry of plan[group] || []) {
    if (!entry.entityId || !Array.isArray(entry.outputs) || !entry.outputs.length) continue;
    const complete = (await Promise.all(entry.outputs.map((item) => exists(browserPathToFile(item.path))))).every(Boolean);
    if (complete) media[entry.entityId] = renderMedia(entry, config.sizes);
  }
  lines.push(`export const ${config.exportName} = Object.freeze(${JSON.stringify(media, null, 2)});`, '');
}

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, `${lines.join('\n')}\n`, 'utf8');

const total = Object.keys(groupConfig).reduce((sum, group) => {
  const entries = plan[group] || [];
  return sum + entries.length;
}, 0);
console.log(`Synced entity media registry from ${total} planned entity entries.`);
